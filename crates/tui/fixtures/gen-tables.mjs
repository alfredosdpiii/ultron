// Generates crates/tui/src/tables.rs: Unicode property ranges exactly as Node's regex engine and the
// get-east-asian-width package (used by packages/tui/src/utils.ts) classify each code point.
// Usage: node crates/tui/fixtures/gen-tables.mjs > crates/tui/src/tables.rs
import { eastAsianWidth } from "get-east-asian-width";
import { cjkBreakRegex, cjkPunctuationRegex } from "../../../packages/tui/src/utils.ts";

const rgi = /^\p{RGI_Emoji}$/v;
const props = {
	ZERO_WIDTH: /^(?:\p{Default_Ignorable_Code_Point}|\p{Control}|\p{Mark})$/v,
	NON_PRINTING: /^(?:\p{Default_Ignorable_Code_Point}|\p{Control}|\p{Format}|\p{Mark})$/v,
	MARK: /^\p{Mark}$/v,
	TERMINAL_SPACING_MARK: /^(?:[\p{Spacing_Mark}--[᜴〮〯]]|[ٟཿါာေဳ-ဵး်-ှ])$/v,
	WIDE: (s, cp) => eastAsianWidth(cp) === 2,
	CJK_BREAK: cjkBreakRegex,
	CJK_PUNCT: cjkPunctuationRegex,
	JS_SPACE: /^\s$/u,
	RGI_SINGLE: rgi,
	RGI_WITH_VS16: (s) => rgi.test(`${s}️`),
	RGI_MODIFIER_BASE: (s) => rgi.test(`${s}\u{1F3FB}`),
	EXTENDED_PICTOGRAPHIC: /^\p{Extended_Pictographic}$/u,
};
let out = "// @generated by crates/tui/fixtures/gen-tables.mjs from Node " + process.version + "; do not edit.\n";
for (const [name, test] of Object.entries(props)) {
	const ranges = [];
	for (let cp = 0; cp <= 0x10ffff; cp++) {
		if (cp >= 0xd800 && cp <= 0xdfff) continue;
		const s = String.fromCodePoint(cp);
		const hit = typeof test === "function" ? test(s, cp) : test.test(s);
		if (!hit) continue;
		const last = ranges[ranges.length - 1];
		if (last && (last[1] === cp - 1 || (last[1] === 0xd7ff && cp === 0xe000))) last[1] = cp;
		else ranges.push([cp, cp]);
	}
	out += `pub(crate) static ${name}: &[(u32, u32)] = &[\n`;
	for (const [a, b] of ranges) out += `    (0x${a.toString(16)}, 0x${b.toString(16)}),\n`;
	out += "];\n";
}
process.stdout.write(out);
