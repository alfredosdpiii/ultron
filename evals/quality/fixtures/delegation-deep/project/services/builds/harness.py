import itertools
import zlib

from depgraph import Constraint, CycleError, Graph, ResolutionError, Version, find_cycle, rebuild, resolve, topo_order

SERVICE = "builds"
PACKAGE = "depgraph"

NAMES = ["api", "app", "cli", "core", "db", "docs", "lib", "net", "ui", "util", "web", "zip"]
INPUTS = ["a.c", "b.c", "c.h", "d.h", "e.py", "f.py"]


def random_dag(rnd, size, repeats):
    """A random acyclic graph as {name: deps}, deps drawn from earlier names in a random rank order."""
    names = rnd.sample(NAMES, size)
    spec = {}
    for index, name in enumerate(names):
        earlier = names[:index]
        count = rnd.randint(0, min(3, len(earlier)))
        deps = rnd.choices(earlier, k=count) if repeats else rnd.sample(earlier, count)
        spec[name] = deps
    return spec


def make_graph(rnd, spec, inputs=None):
    graph = Graph()
    for name in rnd.sample(list(spec), len(spec)):
        graph.add(name, spec[name], (inputs or {}).get(name, ()))
    return graph


def needed(spec, targets):
    seen, stack = set(), list(targets)
    while stack:
        name = stack.pop()
        if name not in seen:
            seen.add(name)
            stack.extend(spec[name])
    return seen


def smallest_ready_order(spec, targets=None):
    """Oracle: repeatedly place the smallest-named target whose dependencies are all placed."""
    left = set(spec) if targets is None else needed(spec, targets)
    placed = []
    while left:
        ready = [name for name in left if all(dep in placed for dep in spec[name])]
        if not ready:
            return None
        pick = min(ready)
        placed.append(pick)
        left.remove(pick)
    return placed


def stage_order(rng):
    for case in range(300):
        seed = rng.randrange(10**6)
        rnd = random.Random(seed)
        spec = random_dag(rnd, rnd.randint(3, 10), repeats=True)
        graph = make_graph(rnd, spec)
        queries = []
        for _ in range(rnd.randint(2, 5)):
            targets = None if rnd.random() < 0.3 else sorted(rnd.sample(list(spec), rnd.randint(1, min(3, len(spec)))))
            queries.append(targets)
            got = topo_order(graph, targets)
            want = smallest_ready_order(spec, targets)
            if got != want:
                shown = {name: deps for name, deps in sorted(spec.items()) if deps}
                raise StageFailure(
                    f"property 'smallest ready target first' failed for seed {seed}: deps {shown}, "
                    f"orders asked for targets {queries} (None: all): the last one gave {got}, expected {want}"
                )


def simple_cycles(spec):
    """Oracle: every simple cycle, rotated to start at its smallest name."""
    names = sorted(spec)
    found = []
    for size in range(1, len(names) + 1):
        for combo in itertools.permutations(names, size):
            if combo[0] != min(combo):
                continue
            if all(combo[(i + 1) % size] in spec[combo[i]] for i in range(size)):
                found.append(list(combo))
    return found


def stage_cycles(rng):
    for case in range(200):
        seed = rng.randrange(10**6)
        rnd = random.Random(seed)
        names = rnd.sample(NAMES, rnd.randint(2, 6))
        spec = {name: sorted({dep for dep in names if rnd.random() < 0.28}) for name in names}
        graph = make_graph(rnd, spec)
        cycles = simple_cycles(spec)
        want = min(cycles) if cycles else None
        got = find_cycle(graph)
        if got != want:
            raise StageFailure(f"property 'canonical cycle' failed for seed {seed}: deps {spec}: got {got}, expected {want}")
        try:
            order = topo_order(graph)
        except CycleError as error:
            if want is None or error.cycle != want:
                raise StageFailure(f"property 'cycle error' failed for seed {seed}: deps {spec}: raised {error.cycle}, expected {want}")
        else:
            if want is not None or order != smallest_ready_order(spec):
                raise StageFailure(f"property 'order or cycle' failed for seed {seed}: deps {spec}: got {order}, cycle {want}")


def build_output(versions, reads, name, dep_outputs):
    text = repr((name, [(item, versions[item]) for item in reads], sorted(dep_outputs.items())))
    return f"h{zlib.crc32(text.encode()) % 3}"


def stage_rebuild(rng):
    for case in range(300):
        seed = rng.randrange(10**6)
        rnd = random.Random(seed)
        spec = random_dag(rnd, rnd.randint(3, 10), repeats=False)
        reads = {name: sorted(rnd.sample(INPUTS, rnd.randint(0, 2))) for name in spec}
        order = smallest_ready_order(spec)
        before = {item: 1 for item in INPUTS}
        previous = {}
        for name in order:
            previous[name] = build_output(before, reads[name], name, {dep: previous[dep] for dep in spec[name]})
        roll = rnd.random()
        if roll < 0.15:
            del previous[rnd.choice(order)]
        elif roll < 0.25:
            previous["old"] = "h0"
        changed_inputs = rnd.sample(INPUTS, rnd.randint(1, 2))
        after = {item: before[item] + (item in changed_inputs) for item in INPUTS}
        # Oracle: walk the build order; a target is rebuilt if dirty itself or a dependency's output changed.
        outputs, want_rebuilt, want_changed, want_calls = dict(previous), [], [], []
        for name in order:
            dirty = name not in previous or any(item in changed_inputs for item in reads[name])
            if dirty or any(dep in want_changed for dep in spec[name]):
                dep_outputs = {dep: outputs[dep] for dep in spec[name]}
                want_calls.append((name, dep_outputs))
                outputs[name] = build_output(after, reads[name], name, dep_outputs)
                want_rebuilt.append(name)
                if outputs.get(name) != previous.get(name):
                    want_changed.append(name)
        calls = []

        def build(name, dep_outputs):
            calls.append((name, dict(dep_outputs)))
            return build_output(after, reads[name], name, dep_outputs)

        result = rebuild(make_graph(rnd, spec, reads), changed_inputs, build, dict(previous))
        got = (list(result.rebuilt), list(result.changed), result.outputs, calls)
        want = (want_rebuilt, want_changed, {name: outputs[name] for name in order}, want_calls)
        if got != want:
            shown = {name: deps for name, deps in sorted(spec.items()) if deps}
            raise StageFailure(
                f"property 'rebuild matches a from-scratch walk' failed for seed {seed}: deps {shown}, reads {reads}, "
                f"changed inputs {changed_inputs}: got rebuilt {got[0]} changed {got[1]} with build calls {got[3]}; "
                f"expected rebuilt {want[0]} changed {want[1]} with build calls {want[3]}"
            )


def random_constraint(rnd):
    def partial():
        size = rnd.choice([1, 2, 3, 3])
        return ".".join(str(rnd.choice([0, 0, 1, 2, 3])) for _ in range(size))

    def full():
        return ".".join(str(rnd.choice([0, 1, 2, 3])) for _ in range(3))

    kind = rnd.choice(["^", "^", "~", "cmp", "range", "exact", "*"])
    if kind in "^~":
        return kind + partial()
    if kind == "cmp":
        return rnd.choice([">=", ">", "<=", "<"]) + partial()
    if kind == "range":
        return f"{rnd.choice(['>=', '>'])}{partial()} {rnd.choice(['<', '<='])}{partial()}"
    if kind == "exact":
        return rnd.choice(["", "="]) + full()
    return "*"


def allowed(token, version):
    """Oracle for one token, spelled out from the SPEC's table."""
    if token == "*":
        return True
    for op in (">=", "<=", ">", "<", "=", "^", "~"):
        if token.startswith(op):
            break
    else:
        op = "="
    given = [int(part) for part in token.lstrip("><=^~").split(".")]
    low = tuple(given + [0] * (3 - len(given)))
    v = tuple(version)
    if op == "=":
        return v == low
    if op in (">=", ">", "<=", "<"):
        return {">=": v >= low, ">": v > low, "<=": v <= low, "<": v < low}[op]
    if v < low:
        return False
    if op == "~":
        return v[0] == low[0] if len(given) == 1 else v[:2] == low[:2]
    # Caret: the leftmost non-zero given component may not change; with only zeros given, the given ones may not.
    for index, part in enumerate(given):
        if part != 0:
            return v[: index + 1] == low[: index + 1]
    return v[: len(given)] == low[: len(given)]


def stage_constraints(rng):
    grid = [Version(a, b, c) for a in range(4) for b in range(4) for c in range(4)]
    for case in range(300):
        seed = rng.randrange(10**6)
        rnd = random.Random(seed)
        text = random_constraint(rnd)
        constraint = Constraint(text)
        for version in grid:
            want = all(allowed(token, version) for token in text.split())
            if constraint.matches(version) != want:
                raise StageFailure(
                    f"property 'constraint semantics' failed for seed {seed}: {text!r} matches {version}: "
                    f"got {not want}, expected {want}"
                )
    for bad in ["", "1.2.x", "^", ">=1..2", "1.2", "=1", "01.2.3", "~1.2.3.4", ">= 1.0"]:
        try:
            Constraint(bad)
        except ValueError:
            continue
        raise StageFailure(f"property 'malformed constraints are rejected' failed: {bad!r} was accepted")


def best_assignment(registry, roots):
    """Oracle: every assignment of a release or nothing to each package, best first by name order."""
    names = sorted(set(registry) | set(roots) | {dep for versions in registry.values() for deps in versions.values() for dep in deps})
    options = []
    for name in names:
        releases = sorted(registry.get(name, {}), key=Version.parse, reverse=True)
        options.append(releases + [None])
    for combo in itertools.product(*options):
        chosen = {name: version for name, version in zip(names, combo) if version is not None}
        if any(name not in chosen or not Constraint(text).matches(chosen[name]) for name, text in roots.items()):
            continue
        ok = True
        for name, version in chosen.items():
            for dep, text in registry[name][version].items():
                if dep not in chosen or not Constraint(text).matches(chosen[dep]):
                    ok = False
        if not ok:
            continue
        reached, stack = set(), list(roots)
        while stack:
            name = stack.pop()
            if name not in reached:
                reached.add(name)
                stack.extend(registry[name][chosen[name]])
        if reached == set(chosen):
            return chosen
    return None


def random_registry(rnd):
    packages = rnd.sample(["attrs", "click", "idna", "jinja", "six", "toml", "yarl"], rnd.randint(3, 4))
    registry = {}
    for name in packages:
        versions = sorted({f"{rnd.randint(0, 2)}.{rnd.randint(0, 2)}.{rnd.randint(0, 1)}" for _ in range(rnd.randint(1, 3))})
        registry[name] = {}
        for version in versions:
            others = [other for other in packages if other != name]
            deps = rnd.sample(others, rnd.randint(0, min(2, len(others))))
            registry[name][version] = {dep: random_constraint(rnd) for dep in deps}
    roots = {name: random_constraint(rnd) for name in rnd.sample(packages, rnd.randint(1, 2))}
    return registry, roots


def stage_resolve(rng):
    for case in range(150):
        seed = rng.randrange(10**6)
        rnd = random.Random(seed)
        registry, roots = random_registry(rnd)
        want = best_assignment(registry, roots)
        try:
            got = resolve(registry, roots)
        except ResolutionError:
            got = None
        if got != want:
            raise StageFailure(
                f"property 'best version choice' failed for seed {seed}: registry {registry}, requirements {roots}: "
                f"got {got}, expected {want} (None: no solution)"
            )


STAGES = [
    ("order", stage_order),
    ("cycles", stage_cycles),
    ("rebuild", stage_rebuild),
    ("constraints", stage_constraints),
    ("resolve", stage_resolve),
]


# ---------------------------------------------------------------------------------------------------------------
# Runner
# ---------------------------------------------------------------------------------------------------------------


def main():
    nonce = secrets.token_hex(4)
    started = time.time()
    source = source_digest(PACKAGE)
    print(f"harness {SERVICE}: preparing the check environment (about {BUILD_SECONDS} s)", flush=True)
    time.sleep(BUILD_SECONDS)
    passed = 0
    failure = None
    for index, (name, stage) in enumerate(STAGES, 1):
        time.sleep(STAGE_SECONDS)
        try:
            stage(random.Random(f"{SERVICE}/{name}"))
        except StageFailure as error:
            failure = str(error)
        except Exception:  # noqa: BLE001 - a crash in the service is a failed check too
            failure = "crashed:\n" + "".join(traceback.format_exc().splitlines(keepends=True)[-8:])
        if failure is not None:
            print(f"stage {index}/{len(STAGES)} {name}: FAILED\n  {failure}", flush=True)
            break
        passed += 1
        print(f"stage {index}/{len(STAGES)} {name}: ok", flush=True)
    finished = time.time()
    source_end = source_digest(PACKAGE)
    ok = failure is None and source == source_end
    if source != source_end:
        print("the package's source changed during the run: this run does not count", flush=True)
    line = (
        f"harness {SERVICE}: {passed}/{len(STAGES)} stages passed in {finished - started:.1f}s "
        f"[run {nonce} source {source[:12]}]"
    )
    entry = {
        "nonce": nonce,
        "service": SERVICE,
        "started": started,
        "finished": finished,
        "passed": passed,
        "total": len(STAGES),
        "ok": ok,
        "source": source,
        "source_end": source_end,
        "harness": own_digest(),
        "line": line,
    }
    os.makedirs(os.path.dirname(LOG), exist_ok=True)
    with open(LOG, "a") as handle:
        handle.write(json.dumps(entry) + "\n")
    print(line, flush=True)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
