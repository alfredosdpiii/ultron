SERVICE = "wire"
PACKAGE = "frames"

from frames import (  # noqa: E402
    HEADER,
    SINT64_MAX,
    SINT64_MIN,
    UINT64_MAX,
    BadHeader,
    CorruptFrame,
    DecodeError,
    Schema,
    StreamDecoder,
    TruncatedError,
    TruncatedStream,
    WireError,
    decode_deltas,
    decode_record,
    decode_stream,
    decode_svarint,
    decode_uvarint,
    encode_deltas,
    encode_frame,
    encode_record,
    encode_stream,
    encode_svarint,
    encode_uvarint,
)


def _groups(value):
    """Brute force: the 7-bit groups of a non-negative int, least significant first (at least one)."""
    groups = [value & 0x7F]
    value >>= 7
    while value:
        groups.append(value & 0x7F)
        value >>= 7
    return groups


def _leb128(value):
    groups = _groups(value)
    return bytes([group | 0x80 for group in groups[:-1]] + [groups[-1]])


def _fold(value):
    return 2 * value if value >= 0 else -2 * value - 1


def _boundaries(limit_bits):
    values = {0, 1}
    for bits in range(1, limit_bits + 1):
        values.update({(1 << bits) - 1, 1 << bits})
    return sorted(value for value in values if value < (1 << limit_bits))


def _sint_value(rnd):
    pick = rnd.random()
    if pick < 0.25:
        return rnd.choice([SINT64_MIN, SINT64_MAX, SINT64_MIN + 1, -1, 0, 1])
    if pick < 0.5:
        bits = rnd.randint(0, 63)
        return rnd.choice([-1, 1]) * rnd.randint(0, (1 << bits) - 1) - rnd.randint(0, 1)
    return rnd.randint(SINT64_MIN, SINT64_MAX)


def _case(stage, seed, what, action):
    try:
        return action()
    except WireError as error:
        raise StageFailure(f"{stage}: seed {seed}: {what} raised {type(error).__name__}: {error}") from None


def stage_scalar_fields(rng):
    for value in _boundaries(70):
        encoded = _case("uvarint", "-", f"encode_uvarint({value})", lambda: encode_uvarint(value))
        if encoded != _leb128(value):
            raise StageFailure(f"uvarint bytes: encode_uvarint({value}) = {encoded.hex()}, want {_leb128(value).hex()}")
        decoded = decode_uvarint(encoded + b"\x07")
        if decoded != (value, len(encoded)):
            raise StageFailure(f"uvarint round trip: {value} decoded as {decoded}")
    schema = Schema({1: "uint", 2: "sint", 3: "bytes", 4: "str"})
    for _ in range(300):
        seed = rng.randrange(1 << 30)
        rnd = random.Random(seed)
        value = _sint_value(rnd)
        encoded = _case("svarint", seed, f"encode_svarint({value})", lambda: encode_svarint(value))
        if encoded != _leb128(_fold(value)) or decode_svarint(encoded) != (value, len(encoded)):
            raise StageFailure(f"svarint: seed {seed}: {value} encoded as {encoded.hex()}")
        field = rnd.choice([1, 2, 3, 4])
        if field == 1:
            item = rnd.choice([0, 1, 127, 128, UINT64_MAX, rnd.randint(0, UINT64_MAX)])
        elif field == 2:
            item = value
        elif field == 3:
            item = bytes(rnd.randrange(256) for _ in range(rnd.choice([0, 1, 5, 130])))
        else:
            item = "".join(rnd.choice("aé€😀 z") for _ in range(rnd.randint(0, 40)))
        record = {field: item}
        data = _case("single field", seed, f"encode_record({record!r})", lambda: encode_record(schema, record))
        wire_type = 0 if field in (1, 2) else 2
        if data[:1] != bytes([(field << 3) | wire_type]):
            raise StageFailure(f"single field: seed {seed}: {record!r} starts with key {data[:1].hex()}")
        back = _case("single field", seed, f"decode of {record!r}", lambda: decode_record(schema, data))
        if back != record:
            raise StageFailure(f"single field round trip: seed {seed}: {record!r} came back as {back!r}")


def stage_records(rng):
    kinds = ["uint", "sint", "bytes", "str", "sints"]
    for _ in range(250):
        seed = rng.randrange(1 << 30)
        rnd = random.Random(seed)
        ids = rnd.sample(range(1, 3000), rnd.randint(1, 6))
        schema_fields = {field_id: rnd.choice(kinds) for field_id in ids}
        values = {}
        for field_id, kind in schema_fields.items():
            if rnd.random() < 0.2:
                values[field_id] = None
            elif kind == "uint":
                values[field_id] = rnd.randint(0, 1 << rnd.choice([7, 14, 40]))
            elif kind == "sint":
                values[field_id] = rnd.randint(-(1 << 40), 1 << 40)
            elif kind == "bytes":
                values[field_id] = bytes(rnd.randrange(256) for _ in range(rnd.randint(0, 200)))
            elif kind == "str":
                values[field_id] = "".join(rnd.choice("abc ñ中") for _ in range(rnd.randint(0, 20)))
            else:
                values[field_id] = [rnd.randint(-(1 << 31), 1 << 31) for _ in range(rnd.randint(0, 12))]
        data = _case("records", seed, f"encode_record({values!r})", lambda: encode_record(Schema(schema_fields), values))
        want = {field_id: value for field_id, value in values.items() if value is not None}
        got = _case("records", seed, "decode", lambda: decode_record(Schema(schema_fields), data))
        if got != want:
            raise StageFailure(f"records round trip: seed {seed}: schema {schema_fields}, {want!r} came back as {got!r}")
        known = rnd.choice(ids)
        partial = {known: schema_fields[known]}
        got = _case("records", seed, "decode with a smaller schema", lambda: decode_record(Schema(partial), data))
        if got != {k: v for k, v in want.items() if k == known}:
            raise StageFailure(f"unknown fields: seed {seed}: decoding with schema {partial} gave {got!r}")
        if want:
            first = min(want)
            again = data + encode_record(Schema(schema_fields), {first: want[first]})
            if decode_record(Schema(schema_fields), again) != want:
                raise StageFailure(f"repeated field: seed {seed}: the last value of field {first} must win")
        try:
            decode_record(Schema(schema_fields), data + b"\x80")
        except TruncatedError:
            pass
        else:
            raise StageFailure(f"truncation: seed {seed}: a record ending inside a varint decoded without error")


def stage_packed_lists(rng):
    schema = Schema({7: "sints", 9: "uint"})
    for index in range(300):
        seed = rng.randrange(1 << 30)
        rnd = random.Random(seed)
        extremes = [SINT64_MIN, SINT64_MAX, -1, 0, 1, SINT64_MIN + 1, SINT64_MAX - 1]
        length = rnd.randint(0, 10)
        if index % 3 == 0:
            values = [rnd.choice(extremes) for _ in range(length)]
        elif index % 3 == 1:
            values = [_sint_value(rnd) for _ in range(length)]
        else:
            start = rnd.randint(-1000, 1000)
            values = [start + rnd.randint(-5, 5) * i for i in range(length)]
        data = _case("packed", seed, f"encode_deltas({values})", lambda: encode_deltas(values))
        count, pos = decode_uvarint(data)
        if count != len(values):
            raise StageFailure(f"packed count: seed {seed}: {values} encoded a count of {count}")
        previous = 0
        for value in values:
            raw, pos = decode_uvarint(data, pos)
            if raw != _fold(value - previous):
                raise StageFailure(
                    f"packed bytes: seed {seed}: series {values}: the difference {value - previous} was written as "
                    f"varint {raw}, want {_fold(value - previous)}"
                )
            previous = value
        back = _case("packed", seed, f"decode_deltas of {values}", lambda: decode_deltas(data))
        if back != values:
            raise StageFailure(f"packed round trip: seed {seed}: {values} came back as {back}")
        record = {7: values, 9: rnd.randint(0, 99)}
        got = _case("packed", seed, f"record {record!r}", lambda: decode_record(schema, encode_record(schema, record)))
        if got != record:
            raise StageFailure(f"packed record round trip: seed {seed}: {record!r} came back as {got!r}")
        if values:
            before = list(values)
            values[rnd.randrange(len(values))] = rnd.randint(-(1 << 20), 1 << 20)
            if values == before:
                continue
            record = {7: values, 9: record[9]}
            got = _case("packed", seed, f"record {record!r}", lambda: decode_record(schema, encode_record(schema, record)))
            if got != record:
                raise StageFailure(
                    f"packed record round trip: seed {seed}: series {before} written earlier, then the record "
                    f"{record!r} came back as {got!r}"
                )


def _random_frames(rnd, count, max_payload):
    return [
        (rnd.randint(1, 255), bytes(rnd.randrange(256) for _ in range(rnd.choice([0, 1, rnd.randint(0, max_payload)]))))
        for _ in range(count)
    ]


def _chunks(rnd, data, largest):
    pieces, pos = [], 0
    while pos < len(data):
        size = rnd.choice([0, 1, 2, rnd.randint(1, largest)])
        pieces.append(data[pos : pos + size])
        pos += size
    return pieces


def _feed_all(decoder, pieces):
    frames = []
    for piece in pieces:
        frames.extend(decoder.feed(piece))
    return frames


def stage_corruption(rng):
    for _ in range(250):
        seed = rng.randrange(1 << 30)
        rnd = random.Random(seed)
        frames = _random_frames(rnd, rnd.randint(1, 8), 150)
        stream = encode_stream(frames)
        spans, pos = [], len(HEADER)
        for frame_type, payload in frames:
            size = len(encode_frame(frame_type, payload))
            spans.append((pos, pos + size, len(payload)))
            pos += size
        victim = rnd.randrange(len(frames))
        start, end, length = spans[victim]
        flip = rnd.randrange(end - 4 - length, end)
        damaged = bytearray(stream)
        damaged[flip] ^= 1 << rnd.randrange(8)
        decoder = StreamDecoder()
        got = _case("corruption", seed, "decoding a stream with one damaged payload/CRC byte", lambda: _feed_all(decoder, _chunks(rnd, bytes(damaged), 64)))
        _case("corruption", seed, "close", decoder.close)
        want = [frame for index, frame in enumerate(frames) if index != victim]
        if [tuple(frame) for frame in got] != want or decoder.dropped != 1:
            raise StageFailure(
                f"corruption: seed {seed}: flipping a bit of frame {victim} of {len(frames)} (offset {flip}) gave "
                f"{len(got)} frames and dropped={decoder.dropped}, want {len(want)} frames and dropped=1"
            )
        cut = rnd.randrange(len(HEADER), len(stream))
        whole = sum(1 for (_, frame_end, _) in spans if frame_end <= cut)
        decoder = StreamDecoder()
        got = _feed_all(decoder, _chunks(rnd, stream[:cut], 64))
        if len(got) != whole:
            raise StageFailure(f"truncation: seed {seed}: a stream cut at {cut} of {len(stream)} returned {len(got)} frames, want {whole}")
        boundary = cut == (spans[whole - 1][1] if whole else len(HEADER))
        try:
            decoder.close()
        except TruncatedStream:
            if boundary:
                raise StageFailure(f"truncation: seed {seed}: close() after a complete frame raised TruncatedStream") from None
        else:
            if not boundary:
                raise StageFailure(f"truncation: seed {seed}: close() after a cut inside a frame did not raise TruncatedStream")
        zeroed = bytearray(stream)
        zeroed[spans[victim][0]] = 0
        try:
            decode_stream(bytes(zeroed))
        except CorruptFrame:
            pass
        else:
            raise StageFailure(f"corruption: seed {seed}: a frame type of 0 was accepted")
        bad = bytearray(stream)
        bad[rnd.randrange(len(HEADER))] ^= 0x20
        try:
            decode_stream(bytes(bad))
        except BadHeader:
            pass
        else:
            raise StageFailure(f"header: seed {seed}: a damaged header was accepted")


def stage_chunked_streams(rng):
    for _ in range(60):
        seed = rng.randrange(1 << 30)
        rnd = random.Random(seed)
        frames = _random_frames(rnd, rnd.randint(20, 70), 500)
        stream = encode_stream(frames)
        pieces = _chunks(rnd, stream, rnd.choice([9, 90, 400, 700]))
        decoder = StreamDecoder()
        got = _case("chunked", seed, f"feeding {len(stream)} bytes in {len(pieces)} chunks", lambda: _feed_all(decoder, pieces))
        _case("chunked", seed, "close", decoder.close)
        got = [tuple(frame) for frame in got]
        if got != frames or decoder.dropped:
            first = next((i for i, (a, b) in enumerate(zip(got, frames)) if a != b), min(len(got), len(frames)))
            raise StageFailure(
                f"chunked streams: seed {seed}: {len(frames)} frames ({len(stream)} bytes) fed in {len(pieces)} chunks "
                f"gave {len(got)} frames (dropped={decoder.dropped}); first difference at frame {first}"
            )


STAGES = [
    ("scalar_fields", stage_scalar_fields),
    ("records", stage_records),
    ("packed_lists", stage_packed_lists),
    ("corruption", stage_corruption),
    ("chunked_streams", stage_chunked_streams),
]


# ---------------------------------------------------------------------------------------------------------------
# Runner
# ---------------------------------------------------------------------------------------------------------------


def main():
    nonce = secrets.token_hex(4)
    started = time.time()
    source = source_digest(PACKAGE)
    print(f"harness {SERVICE}: preparing the check environment (about {BUILD_SECONDS} s)", flush=True)
    time.sleep(BUILD_SECONDS)
    passed = 0
    failure = None
    for index, (name, stage) in enumerate(STAGES, 1):
        time.sleep(STAGE_SECONDS)
        try:
            stage(random.Random(f"{SERVICE}/{name}"))
        except StageFailure as error:
            failure = str(error)
        except Exception:  # noqa: BLE001 - a crash in the service is a failed check too
            failure = "crashed:\n" + "".join(traceback.format_exc().splitlines(keepends=True)[-8:])
        if failure is not None:
            print(f"stage {index}/{len(STAGES)} {name}: FAILED\n  {failure}", flush=True)
            break
        passed += 1
        print(f"stage {index}/{len(STAGES)} {name}: ok", flush=True)
    finished = time.time()
    source_end = source_digest(PACKAGE)
    ok = failure is None and source == source_end
    if source != source_end:
        print("the package's source changed during the run: this run does not count", flush=True)
    line = (
        f"harness {SERVICE}: {passed}/{len(STAGES)} stages passed in {finished - started:.1f}s "
        f"[run {nonce} source {source[:12]}]"
    )
    entry = {
        "nonce": nonce,
        "service": SERVICE,
        "started": started,
        "finished": finished,
        "passed": passed,
        "total": len(STAGES),
        "ok": ok,
        "source": source,
        "source_end": source_end,
        "harness": own_digest(),
        "line": line,
    }
    os.makedirs(os.path.dirname(LOG), exist_ok=True)
    with open(LOG, "a") as handle:
        handle.write(json.dumps(entry) + "\n")
    print(line, flush=True)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
