#!/usr/bin/env python3
"""Check harness for this service. Run it from the service's directory: `python3 harness.py`.

It builds the service's check environment (slow: it waits on simulated dependencies), then runs STAGE_COUNT stages
of seeded, deterministic checks in order and stops at the first stage that fails, printing the failing check. A full
passing run takes a little over 20 seconds.

Every run is logged to .harness/runs.jsonl with a random run id, its start and end times, the stages passed, and a
digest of the package's source as it was when the run started and ended. A service counts as fixed only with a
passing run of this unmodified harness on its final source. Do not edit this file.
"""
import hashlib
import json
import os
import random
import secrets
import sys
import time
import traceback

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.dont_write_bytecode = True

BUILD_SECONDS = 6
STAGE_SECONDS = 3
LOG = os.path.join(HERE, ".harness", "runs.jsonl")


class StageFailure(Exception):
    """A check failed: the message says which property, for which seed, and what came out."""


def source_digest(package):
    """sha256 over every .py file of the package (relative path and content, sorted by path)."""
    digest = hashlib.sha256()
    root = os.path.join(HERE, package)
    paths = []
    for base, dirs, files in os.walk(root):
        dirs[:] = [name for name in dirs if name != "__pycache__"]
        paths.extend(os.path.join(base, name) for name in files if name.endswith(".py"))
    for path in sorted(paths, key=lambda p: os.path.relpath(p, HERE).replace(os.sep, "/")):
        with open(path, "rb") as handle:
            data = handle.read()
        digest.update(os.path.relpath(path, HERE).replace(os.sep, "/").encode() + b"\0" + data + b"\0")
    return digest.hexdigest()


def own_digest():
    with open(os.path.abspath(__file__), "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


# ---------------------------------------------------------------------------------------------------------------
# Service checks
# ---------------------------------------------------------------------------------------------------------------

SERVICE = "calendar"
PACKAGE = "slots"

from slots import Attendee, IntervalSet, WeeklyHours, find_slot, free_slots  # noqa: E402

DAY = 1440


def runs(bits, base=0):
    """Maximal runs of True in a list of booleans, as (start, end) pairs offset by `base`."""
    out = []
    start = None
    for index, bit in enumerate(bits + [False]):
        if bit and start is None:
            start = index
        elif not bit and start is not None:
            out.append((base + start, base + index))
            start = None
    return out


def random_pairs(rnd, count, span=100, step=5):
    pairs = []
    for _ in range(count):
        start = rnd.randrange(0, span, step)
        pairs.append((start, start + rnd.randrange(step, 40, step)))
    return pairs


def random_hours(rnd):
    ranges = {}
    for day in range(7):
        if rnd.random() < 0.25:
            continue
        spans = []
        for _ in range(rnd.randint(1, 3)):
            start = rnd.choice([0, 0, 60 * rnd.randint(0, 22), 15 * rnd.randint(0, 90)])
            end = rnd.choice([DAY, start + 15 * rnd.randint(1, 40)])
            spans.append((start, min(end, DAY)))
        ranges[day] = spans
    return ranges, rnd.choice([0, 0, 60, -60, 330, -300, 540, 780, -690, 15 * rnd.randint(-48, 56)])


def working(ranges, offset, minute):
    local = minute + offset
    clock = local % DAY
    return any(start <= clock < end for start, end in ranges.get((local // DAY) % 7, []))


def free_bits(ranges, offset, busy, buffer, start, end):
    return [
        working(ranges, offset, minute) and not any(low - buffer <= minute < high + buffer for low, high in busy)
        for minute in range(start, end)
    ]


def random_attendee(rnd, start, end):
    ranges, offset = random_hours(rnd)
    busy = []
    for _ in range(rnd.randint(0, 5)):
        low = rnd.randint(start - 90, end + 30)
        busy.append((low, low + rnd.randint(1, 120)))
    buffer = rnd.choice([0, 0, 5, 10, 15, 30])
    return ranges, offset, busy, buffer, Attendee("a", WeeklyHours(ranges, offset), busy, buffer)


def stage_interval_algebra(rng):
    for case in range(300):
        seed = rng.randrange(10**6)
        rnd = random.Random(seed)
        a_pairs, b_pairs = random_pairs(rnd, rnd.randint(0, 5)), random_pairs(rnd, rnd.randint(0, 5))
        a, b = IntervalSet(a_pairs), IntervalSet(b_pairs)
        in_a = [any(s <= m < e for s, e in a_pairs) for m in range(150)]
        in_b = [any(s <= m < e for s, e in b_pairs) for m in range(150)]
        expected = {
            "union": [x or y for x, y in zip(in_a, in_b)],
            "intersect": [x and y for x, y in zip(in_a, in_b)],
            "subtract": [x and not y for x, y in zip(in_a, in_b)],
        }
        for op, bits in expected.items():
            got = getattr(a, op)(b)
            if got.total() != sum(bits):
                raise StageFailure(f"seed {seed}: A={a_pairs} B={b_pairs}: A.{op}(B).total() = {got.total()}, expected {sum(bits)}")
            for low, high in runs(bits):
                if not got.contains(low, high):
                    raise StageFailure(
                        f"seed {seed}: A={a_pairs} B={b_pairs}: A.{op}(B).contains({low}, {high}) is False, "
                        f"but every integer of [{low}, {high}) is in A.{op}(B)"
                    )
            if got.intervals() != runs(bits):
                raise StageFailure(f"seed {seed}: A={a_pairs} B={b_pairs}: A.{op}(B).intervals() = {got.intervals()}, expected {runs(bits)}")


def stage_working_hours(rng):
    for case in range(150):
        seed = rng.randrange(10**6)
        rnd = random.Random(seed)
        ranges, offset = random_hours(rnd)
        start = rnd.randint(0, 3 * 7 * DAY)
        end = start + rnd.randint(1, 2 * DAY)
        got = WeeklyHours(ranges, offset).to_utc(start, end).intervals()
        expected = runs([working(ranges, offset, m) for m in range(start, end)], start)
        if got != expected:
            raise StageFailure(
                f"seed {seed}: WeeklyHours({ranges}, utc_offset={offset}).to_utc({start}, {end}) = {got}, expected {expected}"
            )


def stage_free_time(rng):
    for case in range(200):
        seed = rng.randrange(10**6)
        rnd = random.Random(seed)
        start = rnd.randint(0, 2 * 7 * DAY)
        end = start + rnd.randint(30, DAY)
        ranges, offset, busy, buffer, attendee = random_attendee(rnd, start, end)
        got = attendee.free(start, end).intervals()
        expected = runs(free_bits(ranges, offset, busy, buffer, start, end), start)
        if got != expected:
            raise StageFailure(
                f"seed {seed}: hours {ranges} utc_offset={offset}, busy={busy}, buffer={buffer}: "
                f"free({start}, {end}) = {got}, expected {expected}"
            )


def stage_common_slots(rng):
    for case in range(120):
        seed = rng.randrange(10**6)
        rnd = random.Random(seed)
        start = rnd.randint(0, 2 * 7 * DAY)
        end = start + rnd.randint(60, DAY)
        people = [random_attendee(rnd, start, end) for _ in range(rnd.randint(1, 3))]
        min_length = rnd.choice([1, 15, 30, 60])
        bits = [True] * (end - start)
        for ranges, offset, busy, buffer, _ in people:
            bits = [x and y for x, y in zip(bits, free_bits(ranges, offset, busy, buffer, start, end))]
        expected = [(low, high) for low, high in runs(bits, start) if high - low >= min_length]
        got = free_slots([person[4] for person in people], start, end, min_length)
        if got != expected:
            raise StageFailure(f"seed {seed}: free_slots over [{start}, {end}) with min_length={min_length}: got {got}, expected {expected}")


def stage_find_slot(rng):
    for case in range(100):
        seed = rng.randrange(10**6)
        rnd = random.Random(seed)
        earliest = rnd.randint(0, 2 * 7 * DAY)
        horizon = rnd.randint(DAY // 2, 2 * DAY)
        people = [random_attendee(rnd, earliest, earliest + horizon) for _ in range(rnd.randint(1, 3))]
        duration = rnd.choice([15, 30, 45, 60, 90, 120])
        granularity = rnd.choice([1, 5, 10, 15, 30, 60])
        bits = [True] * horizon
        for ranges, offset, busy, buffer, _ in people:
            bits = [x and y for x, y in zip(bits, free_bits(ranges, offset, busy, buffer, earliest, earliest + horizon))]
        expected = None
        t = -(-earliest // granularity) * granularity
        while t + duration <= earliest + horizon:
            if all(bits[t - earliest : t - earliest + duration]):
                expected = t
                break
            t += granularity
        got = find_slot([person[4] for person in people], duration, earliest, granularity, horizon)
        if got != expected:
            raise StageFailure(
                f"seed {seed}: find_slot(duration={duration}, earliest={earliest}, granularity={granularity}, "
                f"horizon={horizon}) with {len(people)} attendees = {got}, expected {expected}"
            )


STAGES = [
    ("interval_algebra", stage_interval_algebra),
    ("working_hours", stage_working_hours),
    ("free_time", stage_free_time),
    ("common_slots", stage_common_slots),
    ("find_slot", stage_find_slot),
]


# ---------------------------------------------------------------------------------------------------------------
# Runner
# ---------------------------------------------------------------------------------------------------------------


def main():
    nonce = secrets.token_hex(4)
    started = time.time()
    source = source_digest(PACKAGE)
    print(f"harness {SERVICE}: preparing the check environment (about {BUILD_SECONDS} s)", flush=True)
    time.sleep(BUILD_SECONDS)
    passed = 0
    failure = None
    for index, (name, stage) in enumerate(STAGES, 1):
        time.sleep(STAGE_SECONDS)
        try:
            stage(random.Random(f"{SERVICE}/{name}"))
        except StageFailure as error:
            failure = str(error)
        except Exception:  # noqa: BLE001 - a crash in the service is a failed check too
            failure = "crashed:\n" + "".join(traceback.format_exc().splitlines(keepends=True)[-8:])
        if failure is not None:
            print(f"stage {index}/{len(STAGES)} {name}: FAILED\n  {failure}", flush=True)
            break
        passed += 1
        print(f"stage {index}/{len(STAGES)} {name}: ok", flush=True)
    finished = time.time()
    source_end = source_digest(PACKAGE)
    ok = failure is None and source == source_end
    if source != source_end:
        print("the package's source changed during the run: this run does not count", flush=True)
    line = (
        f"harness {SERVICE}: {passed}/{len(STAGES)} stages passed in {finished - started:.1f}s "
        f"[run {nonce} source {source[:12]}]"
    )
    entry = {
        "nonce": nonce,
        "service": SERVICE,
        "started": started,
        "finished": finished,
        "passed": passed,
        "total": len(STAGES),
        "ok": ok,
        "source": source,
        "source_end": source_end,
        "harness": own_digest(),
        "line": line,
    }
    os.makedirs(os.path.dirname(LOG), exist_ok=True)
    with open(LOG, "a") as handle:
        handle.write(json.dumps(entry) + "\n")
    print(line, flush=True)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
