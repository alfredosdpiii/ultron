#!/usr/bin/env python3
"""Check harness for this service. Run it from the service's directory: `python3 harness.py`.

It builds the service's check environment (slow: it waits on simulated dependencies), then runs STAGE_COUNT stages
of seeded, deterministic checks in order and stops at the first stage that fails, printing the failing check. A full
passing run takes a little over 20 seconds.

Every run is logged to .harness/runs.jsonl with a random run id, its start and end times, the stages passed, and a
digest of the package's source as it was when the run started and ended. A service counts as fixed only with a
passing run of this unmodified harness on its final source. Do not edit this file.
"""
import hashlib
import json
import os
import random
import secrets
import sys
import time
import traceback

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.dont_write_bytecode = True

BUILD_SECONDS = 6
STAGE_SECONDS = 3
LOG = os.path.join(HERE, ".harness", "runs.jsonl")


class StageFailure(Exception):
    """A check failed: the message says which property, for which seed, and what came out."""


def source_digest(package):
    """sha256 over every .py file of the package (relative path and content, sorted by path)."""
    digest = hashlib.sha256()
    root = os.path.join(HERE, package)
    paths = []
    for base, dirs, files in os.walk(root):
        dirs[:] = [name for name in dirs if name != "__pycache__"]
        paths.extend(os.path.join(base, name) for name in files if name.endswith(".py"))
    for path in sorted(paths, key=lambda p: os.path.relpath(p, HERE).replace(os.sep, "/")):
        with open(path, "rb") as handle:
            data = handle.read()
        digest.update(os.path.relpath(path, HERE).replace(os.sep, "/").encode() + b"\0" + data + b"\0")
    return digest.hexdigest()


def own_digest():
    with open(os.path.abspath(__file__), "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


# ---------------------------------------------------------------------------------------------------------------
# Service checks
# ---------------------------------------------------------------------------------------------------------------
SERVICE = "patch"
PACKAGE = "linediff"

from linediff import (  # noqa: E402
    Hunk,
    PatchError,
    apply_hunks,
    apply_patch,
    diff_lines,
    diffstat,
    format_hunks,
    format_unified,
    make_hunks,
    parse_unified,
    reverse_hunks,
)

WORDS = ["alpha", "beta", "gamma", "", "-- x", "++ y", "@@ z", " delta", "beta"]


def random_file(r, words, low=0, high=10):
    return [r.choice(words) for _ in range(r.randint(low, high))]


def mutate(r, a, words):
    """A copy of `a` with a few random deletions, insertions and replacements."""
    b = list(a)
    for _ in range(r.randint(0, 4)):
        kind = r.random()
        if kind < 0.35 and b:
            del b[r.randrange(len(b))]
        elif kind < 0.7:
            b.insert(r.randint(0, len(b)), r.choice(words))
        elif b:
            b[r.randrange(len(b))] = r.choice(words)
    return b


def outcome(action):
    try:
        return action()
    except (ValueError, PatchError) as error:
        return f"{type(error).__name__}: {error}"


def lcs_brute(a, b, memo=None):
    memo = {} if memo is None else memo
    key = (len(a), len(b))
    if key not in memo:
        if not a or not b:
            memo[key] = 0
        elif a[-1] == b[-1]:
            memo[key] = lcs_brute(a[:-1], b[:-1], memo) + 1
        else:
            memo[key] = max(lcs_brute(a[:-1], b, memo), lcs_brute(a, b[:-1], memo))
    return memo[key]


def cases(rng, count):
    for _ in range(count):
        seed = rng.randrange(10**9)
        yield seed, random.Random(seed)


def stage_roundtrip(rng):
    for seed, r in cases(rng, 300):
        a = random_file(r, WORDS)
        b = mutate(r, a, WORDS)
        context = r.randint(0, 3)
        text = format_unified(a, b, context)
        if (text == "") != (a == b):
            raise StageFailure(f"seed {seed}: format_unified(a, b, {context}) is {'empty' if not text else 'not empty'} for a={a!r} b={b!r}")
        got = outcome(lambda: apply_patch(a, text))
        if got != b:
            raise StageFailure(
                f"seed {seed}: apply_patch(a, format_unified(a, b, context={context})) != b\n"
                f"  a={a!r}\n  b={b!r}\n  got={got!r}"
            )


def stage_minimal(rng):
    for seed, r in cases(rng, 300):
        a = random_file(r, WORDS[:3], 0, 9)
        b = random_file(r, WORDS[:3], 0, 9)
        ops = diff_lines(a, b)
        i = j = 0
        previous = None
        for op in ops:
            tag, i1, i2, j1, j2 = op
            if (i1, j1) != (i, j) or tag == previous or (i2 - i1) + (j2 - j1) == 0:
                raise StageFailure(f"seed {seed}: diff_lines({a!r}, {b!r}) is not a contiguous edit script: {ops!r}")
            if tag == "equal" and a[i1:i2] != b[j1:j2]:
                raise StageFailure(f"seed {seed}: diff_lines({a!r}, {b!r}) keeps unequal lines in {op!r}")
            if previous == "insert" and tag == "delete":
                raise StageFailure(f"seed {seed}: diff_lines({a!r}, {b!r}) puts an insert before a delete: {ops!r}")
            i, j, previous = i2, j2, tag
        if (i, j) != (len(a), len(b)):
            raise StageFailure(f"seed {seed}: diff_lines({a!r}, {b!r}) does not cover both files: {ops!r}")
        kept = sum(op.i2 - op.i1 for op in ops if op.tag == "equal")
        best = lcs_brute(a, b)
        if kept != best:
            raise StageFailure(f"seed {seed}: diff_lines({a!r}, {b!r}) keeps {kept} lines, a longest common subsequence has {best}")


def check_shape(where, a, b, context, hunks):
    for number, hunk in enumerate(hunks, 1):
        try:
            hunk.check()
        except ValueError as error:
            raise StageFailure(f"{where}\n  hunk {number}: {error}") from None
        if not hunk.changed():
            raise StageFailure(f"{where}\n  hunk {number} has no changes")
        tags = "".join(tag for tag, _ in hunk.lines)
        lead, trail = len(tags) - len(tags.lstrip(" ")), len(tags) - len(tags.rstrip(" "))
        anchor = hunk.old_anchor()
        if lead > context or trail > context:
            raise StageFailure(f"{where}\n  hunk {number} {hunk.header()} has {lead} leading and {trail} trailing context lines")
        if lead < context and anchor != 0:
            raise StageFailure(f"{where}\n  hunk {number} {hunk.header()} shows too little leading context")
        if trail < context and anchor + hunk.old_count != len(a):
            raise StageFailure(f"{where}\n  hunk {number} {hunk.header()} shows too little trailing context")
        inner = max((len(run) for run in tags.strip(" ").replace("+", "-").split("-")), default=0)
        if inner > 2 * context:
            raise StageFailure(f"{where}\n  hunk {number} {hunk.header()} keeps {inner} unchanged lines between two changes")
        if hunk.old_lines() != list(a[anchor:anchor + hunk.old_count]) or hunk.new_lines() != list(b[hunk.new_anchor():hunk.new_anchor() + hunk.new_count]):
            raise StageFailure(f"{where}\n  hunk {number} {hunk.header()} does not match the files at its header positions")
    for number in range(1, len(hunks)):
        before, after = hunks[number - 1], hunks[number]
        if after.old_anchor() <= before.old_anchor() + before.old_count:
            raise StageFailure(f"{where}\n  hunks {number} {before.header()} and {number + 1} {after.header()} overlap or touch")
    again = outcome(lambda: parse_unified(format_hunks(hunks)))
    if again != hunks:
        raise StageFailure(f"{where}\n  parse_unified(format_hunks(hunks)) differs: {again!r}")


def stage_hunk_shape(rng):
    for seed, r in cases(rng, 120):
        a = random_file(r, WORDS, 0, 16)
        b = mutate(r, mutate(r, a, WORDS), WORDS)
        for context in r.sample(range(4), 4):
            hunks = make_hunks(a, b, context)
            check_shape(f"seed {seed}: make_hunks(a, b, context={context})\n  a={a!r}\n  b={b!r}", a, b, context, hunks)


def stage_reverse(rng):
    for seed, r in cases(rng, 300):
        a = random_file(r, WORDS, 0, 14)
        b = mutate(r, a, WORDS)
        context = r.randint(0, 3)
        hunks = make_hunks(a, b, context)
        back = reverse_hunks(hunks)
        where = f"seed {seed}: context={context}\n  a={a!r}\n  b={b!r}"
        got = outcome(lambda: apply_hunks(b, back))
        if got != a:
            raise StageFailure(f"{where}\n  apply_hunks(b, reverse_hunks(make_hunks(a, b))) != a: got {got!r}")
        if reverse_hunks(back) != hunks:
            raise StageFailure(f"{where}\n  reverse_hunks twice does not give the hunks back")
        added, removed = diffstat(hunks)
        if diffstat(back) != (removed, added):
            raise StageFailure(f"{where}\n  diffstat of the reversed hunks is not swapped")


def expected_apply(lines, hunks):
    """Brute-force model of the SPEC's placement rule."""
    out, floor, offset = [], 0, 0
    for index, hunk in enumerate(hunks):
        old = [text for tag, text in hunk.lines if tag != "+"]
        anchor = hunk.old_start - 1 if hunk.old_count else hunk.old_start
        want = anchor + offset
        found = [p for p in range(floor, len(lines) - len(old) + 1) if lines[p:p + len(old)] == old]
        if not found:
            return f"PatchError at hunk {index}"
        pos = min(found, key=lambda p: (abs(p - want), p))
        out += lines[floor:pos] + [text for tag, text in hunk.lines if tag != "-"]
        floor, offset = pos + len(old), pos - anchor
    return out + lines[floor:]


def stage_offset(rng):
    words = ["x", "y", "z"]
    for seed, r in cases(rng, 400):
        a = random_file(r, words, 2, 14)
        b = mutate(r, a, words)
        context = r.randint(1, 2)
        hunks = make_hunks(a, b, context)
        target = list(a)
        for _ in range(r.randint(1, 3)):
            if r.random() < 0.5 and target:
                del target[r.randrange(len(target))]
            else:
                target.insert(r.randint(0, len(target)), r.choice(words))
        want = expected_apply(target, hunks)
        try:
            got = apply_hunks(target, hunks)
        except PatchError as error:
            got = f"PatchError at hunk {error.index}"
        if got != want:
            raise StageFailure(
                f"seed {seed}: hunks of make_hunks(a, b, context={context}) applied to a moved copy of a\n"
                f"  a={a!r}\n  b={b!r}\n  copy={target!r}\n  hunks={[h.header() for h in hunks]}\n  got={got!r}\n  expected={want!r}"
            )


STAGES = [
    ("roundtrip", stage_roundtrip),
    ("minimal", stage_minimal),
    ("hunk_shape", stage_hunk_shape),
    ("reverse", stage_reverse),
    ("offset", stage_offset),
]


# ---------------------------------------------------------------------------------------------------------------
# Runner
# ---------------------------------------------------------------------------------------------------------------


def main():
    nonce = secrets.token_hex(4)
    started = time.time()
    source = source_digest(PACKAGE)
    print(f"harness {SERVICE}: preparing the check environment (about {BUILD_SECONDS} s)", flush=True)
    time.sleep(BUILD_SECONDS)
    passed = 0
    failure = None
    for index, (name, stage) in enumerate(STAGES, 1):
        time.sleep(STAGE_SECONDS)
        try:
            stage(random.Random(f"{SERVICE}/{name}"))
        except StageFailure as error:
            failure = str(error)
        except Exception:  # noqa: BLE001 - a crash in the service is a failed check too
            failure = "crashed:\n" + "".join(traceback.format_exc().splitlines(keepends=True)[-8:])
        if failure is not None:
            print(f"stage {index}/{len(STAGES)} {name}: FAILED\n  {failure}", flush=True)
            break
        passed += 1
        print(f"stage {index}/{len(STAGES)} {name}: ok", flush=True)
    finished = time.time()
    source_end = source_digest(PACKAGE)
    ok = failure is None and source == source_end
    if source != source_end:
        print("the package's source changed during the run: this run does not count", flush=True)
    line = (
        f"harness {SERVICE}: {passed}/{len(STAGES)} stages passed in {finished - started:.1f}s "
        f"[run {nonce} source {source[:12]}]"
    )
    entry = {
        "nonce": nonce,
        "service": SERVICE,
        "started": started,
        "finished": finished,
        "passed": passed,
        "total": len(STAGES),
        "ok": ok,
        "source": source,
        "source_end": source_end,
        "harness": own_digest(),
        "line": line,
    }
    os.makedirs(os.path.dirname(LOG), exist_ok=True)
    with open(LOG, "a") as handle:
        handle.write(json.dumps(entry) + "\n")
    print(line, flush=True)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
