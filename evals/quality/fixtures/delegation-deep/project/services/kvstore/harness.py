#!/usr/bin/env python3
"""Check harness for this service. Run it from the service's directory: `python3 harness.py`.

It builds the service's check environment (slow: it waits on simulated dependencies), then runs STAGE_COUNT stages
of seeded, deterministic checks in order and stops at the first stage that fails, printing the failing check. A full
passing run takes a little over 20 seconds.

Every run is logged to .harness/runs.jsonl with a random run id, its start and end times, the stages passed, and a
digest of the package's source as it was when the run started and ended. A service counts as fixed only with a
passing run of this unmodified harness on its final source. Do not edit this file.
"""
import hashlib
import json
import os
import random
import secrets
import sys
import time
import traceback

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.dont_write_bytecode = True

BUILD_SECONDS = 6
STAGE_SECONDS = 3
LOG = os.path.join(HERE, ".harness", "runs.jsonl")


class StageFailure(Exception):
    """A check failed: the message says which property, for which seed, and what came out."""


def source_digest(package):
    """sha256 over every .py file of the package (relative path and content, sorted by path)."""
    digest = hashlib.sha256()
    root = os.path.join(HERE, package)
    paths = []
    for base, dirs, files in os.walk(root):
        dirs[:] = [name for name in dirs if name != "__pycache__"]
        paths.extend(os.path.join(base, name) for name in files if name.endswith(".py"))
    for path in sorted(paths, key=lambda p: os.path.relpath(p, HERE).replace(os.sep, "/")):
        with open(path, "rb") as handle:
            data = handle.read()
        digest.update(os.path.relpath(path, HERE).replace(os.sep, "/").encode() + b"\0" + data + b"\0")
    return digest.hexdigest()


def own_digest():
    with open(os.path.abspath(__file__), "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


# ---------------------------------------------------------------------------------------------------------------
# Service checks
# ---------------------------------------------------------------------------------------------------------------

SERVICE = "kvstore"
PACKAGE = "segstore"

from segstore import Store, recover  # noqa: E402

KEYS = [f"{group}/{name}" for group in ("acct", "cart", "user") for name in ("a", "b", "c", "d", "e")]


def _value(r):
    return bytes(r.randrange(256) for _ in range(r.randint(0, 14)))


def _random_op(r):
    roll = r.random()
    if roll < 0.62:
        return ("put", r.choice(KEYS), _value(r))
    if roll < 0.85:
        return ("delete", r.choice(KEYS))
    return ("get", r.choice(KEYS))


def _apply(store, model, op):
    """Apply one op to the store and the model; returns (got, expected) for reads, else None."""
    if op[0] == "put":
        store.put(op[1], op[2])
        model[op[1]] = op[2]
        return None
    if op[0] == "delete":
        got, expected = store.delete(op[1]), op[1] in model
        model.pop(op[1], None)
        return (got, expected) if got != expected else None
    got, expected = store.get(op[1]), model.get(op[1])
    return (got, expected) if got != expected else None


def _short(ops):
    return "; ".join(
        f"put({op[1]!r}, {op[2]!r})" if op[0] == "put" else f"{op[0]}({op[1]!r})" for op in ops
    )


def _contents(store):
    return dict(store.scan())


def _diff(got, expected):
    for key in sorted(set(got) | set(expected)):
        if got.get(key) != expected.get(key):
            return f"key {key!r}: store has {got.get(key)!r}, expected {expected.get(key)!r}"
    return "contents differ"


def _run(store, model, ops, seed, limit, what):
    for step, op in enumerate(ops):
        try:
            mismatch = _apply(store, model, op)
        except Exception as error:  # noqa: BLE001
            raise StageFailure(
                f"{what}: seed {seed}, segment limit {limit}: op {step + 1} {_short([op])} raised "
                f"{type(error).__name__}: {error} (previous ops: {_short(ops[max(0, step - 4):step])})"
            ) from None
        if mismatch is not None:
            raise StageFailure(
                f"{what}: seed {seed}, segment limit {limit}: op {step + 1} {_short([op])} returned {mismatch[0]!r}, "
                f"expected {mismatch[1]!r} (previous ops: {_short(ops[max(0, step - 4):step])})"
            )


def _check_contents(store, model, seed, limit, what):
    try:
        got = _contents(store)
    except Exception as error:  # noqa: BLE001
        raise StageFailure(f"{what}: seed {seed}, segment limit {limit}: scan() raised {type(error).__name__}: {error}") from None
    if got != model:
        raise StageFailure(f"{what}: seed {seed}, segment limit {limit}: {_diff(got, model)}")
    for key, value in model.items():
        try:
            got_value = store.get(key)
        except Exception as error:  # noqa: BLE001
            raise StageFailure(f"{what}: seed {seed}, segment limit {limit}: get({key!r}) raised {type(error).__name__}: {error}") from None
        if got_value != value:
            raise StageFailure(f"{what}: seed {seed}, segment limit {limit}: get({key!r}) returned {got_value!r}, expected {value!r}")


def stage_basic_ops(rng):
    """put/get/delete against a dict, with segments small enough to roll over often."""
    for _ in range(300):
        seed = rng.randrange(10**6)
        r = random.Random(seed)
        limit = r.randint(40, 140)
        store, model = Store(limit), {}
        ops = [_random_op(r) for _ in range(r.randint(10, 60))]
        _run(store, model, ops, seed, limit, "read after writes")
        _check_contents(store, model, seed, limit, "read after writes")


def stage_scan_ranges(rng):
    """scan() with bounds and prefixes against a sorted dict."""
    for _ in range(250):
        seed = rng.randrange(10**6)
        r = random.Random(seed)
        limit = r.randint(60, 200)
        store, model = Store(limit), {}
        _run(store, model, [_random_op(r) for _ in range(40)], seed, limit, "scan setup")
        for _ in range(8):
            start = r.choice([None, r.choice(KEYS), r.choice(KEYS)[:3]])
            end = r.choice([None, r.choice(KEYS), "user/c"])
            prefix = r.choice([None, "", "acct/", "cart/", "user/", "user/b", "x"])
            expected = [
                (key, model[key])
                for key in sorted(model)
                if (start is None or key >= start) and (end is None or key < end) and (not prefix or key.startswith(prefix))
            ]
            got = store.scan(start=start, end=end, prefix=prefix)
            if got != expected:
                raise StageFailure(
                    f"scan order and bounds: seed {seed}: scan(start={start!r}, end={end!r}, prefix={prefix!r}) returned "
                    f"keys {[key for key, _ in got]}, expected {[key for key, _ in expected]}"
                )


def stage_compaction(rng):
    """Contents survive compaction unchanged, with writes before, between and after compactions."""
    for _ in range(250):
        seed = rng.randrange(10**6)
        r = random.Random(seed)
        limit = r.randint(50, 160)
        store, model = Store(limit), {}
        for round_ in range(r.randint(1, 3)):
            _run(store, model, [_random_op(r) for _ in range(r.randint(15, 50))], seed, limit, "compaction")
            before = store.stats()
            try:
                store.compact()
            except Exception as error:  # noqa: BLE001
                raise StageFailure(f"compaction: seed {seed}, segment limit {limit}: compact() raised {type(error).__name__}: {error}") from None
            after = store.stats()
            if after["bytes"] > before["bytes"] or after["segments"] > before["segments"]:
                raise StageFailure(f"compaction: seed {seed}, segment limit {limit}: compaction grew the store from {before} to {after}")
            _check_contents(store, model, seed, limit, f"contents after compaction {round_ + 1}")
        _run(store, model, [_random_op(r) for _ in range(10)], seed, limit, "writes after compaction")
        _check_contents(store, model, seed, limit, "writes after compaction")


def _landing(store, before):
    """Where the last op's record landed: (segment id, end offset), or None when it wrote nothing."""
    after = store.stats()
    if after["bytes"] == before["bytes"] and after["segments"] == before["segments"]:
        return None
    segment_id, data = store.export()[-1]
    return segment_id, len(data)


def stage_torn_recovery(rng):
    """Recovery after the last segment was cut short or damaged keeps exactly the records before the damage."""
    for _ in range(250):
        seed = rng.randrange(10**6)
        r = random.Random(seed)
        limit = r.randint(50, 160)
        store = Store(limit)
        history = []
        for op in [_random_op(r) for _ in range(r.randint(5, 45))]:
            if op[0] == "get":
                continue
            before = store.stats()
            if op[0] == "put":
                store.put(op[1], op[2])
            else:
                store.delete(op[1])
            landed = _landing(store, before)
            if landed is not None:
                history.append((op, landed))
        exported = store.export()
        last_id, data = exported[-1]
        kind = r.choice(["cut", "cut", "flip"]) if data else "cut"
        if kind == "cut":
            ends = [0] + [end for _, (segment_id, end) in history if segment_id == last_id]
            boundary = r.choice(ends)
            damage = min(len(data), max(0, boundary + r.choice([0, 0, 1, 11, 12, -1])))
            if damage == len(data):
                damage = len(data) - (1 if data else 0)
            damaged = data[:damage]
            limit_at = damage
        else:
            damage = r.randrange(len(data))
            damaged = data[:damage] + bytes([data[damage] ^ (1 << r.randrange(8))]) + data[damage + 1 :]
            limit_at = damage
        exported[-1] = (last_id, damaged)
        model = {}
        for op, (segment_id, end) in history:
            if segment_id != last_id or end <= limit_at:
                if op[0] == "put":
                    model[op[1]] = op[2]
                else:
                    model.pop(op[1], None)
        what = f"recovery after a {'truncated' if kind == 'cut' else 'damaged'} last segment (byte {damage} of {len(data)})"
        try:
            recovered = recover(exported, limit)
        except Exception as error:  # noqa: BLE001
            raise StageFailure(f"{what}: seed {seed}, segment limit {limit}: recover() raised {type(error).__name__}: {error}") from None
        _check_contents(recovered, model, seed, limit, what)
        _run(recovered, model, [_random_op(r) for _ in range(12)], seed, limit, f"writes after {what}")
        _check_contents(recovered, model, seed, limit, f"writes after {what}")


def stage_compact_recover(rng):
    """A store rebuilt from its exported segments (in any order) matches the store, compactions included."""
    for _ in range(250):
        seed = rng.randrange(10**6)
        r = random.Random(seed)
        limit = r.randint(50, 160)
        store, model = Store(limit), {}
        for _ in range(r.randint(1, 3)):
            _run(store, model, [_random_op(r) for _ in range(r.randint(10, 40))], seed, limit, "compact then recover")
            store.compact()
        _run(store, model, [_random_op(r) for _ in range(r.randint(0, 20))], seed, limit, "compact then recover")
        exported = store.export()
        r.shuffle(exported)
        try:
            recovered = recover(exported, limit)
        except Exception as error:  # noqa: BLE001
            raise StageFailure(f"compact then recover: seed {seed}, segment limit {limit}: recover() raised {type(error).__name__}: {error}") from None
        _check_contents(recovered, model, seed, limit, "compact then recover")
        _run(recovered, model, [_random_op(r) for _ in range(10)], seed, limit, "writes after compact then recover")
        _check_contents(recovered, model, seed, limit, "writes after compact then recover")


STAGES = [
    ("basic_ops", stage_basic_ops),
    ("scan_ranges", stage_scan_ranges),
    ("compaction", stage_compaction),
    ("torn_recovery", stage_torn_recovery),
    ("compact_recover", stage_compact_recover),
]


# ---------------------------------------------------------------------------------------------------------------
# Runner
# ---------------------------------------------------------------------------------------------------------------


def main():
    nonce = secrets.token_hex(4)
    started = time.time()
    source = source_digest(PACKAGE)
    print(f"harness {SERVICE}: preparing the check environment (about {BUILD_SECONDS} s)", flush=True)
    time.sleep(BUILD_SECONDS)
    passed = 0
    failure = None
    for index, (name, stage) in enumerate(STAGES, 1):
        time.sleep(STAGE_SECONDS)
        try:
            stage(random.Random(f"{SERVICE}/{name}"))
        except StageFailure as error:
            failure = str(error)
        except Exception:  # noqa: BLE001 - a crash in the service is a failed check too
            failure = "crashed:\n" + "".join(traceback.format_exc().splitlines(keepends=True)[-8:])
        if failure is not None:
            print(f"stage {index}/{len(STAGES)} {name}: FAILED\n  {failure}", flush=True)
            break
        passed += 1
        print(f"stage {index}/{len(STAGES)} {name}: ok", flush=True)
    finished = time.time()
    source_end = source_digest(PACKAGE)
    ok = failure is None and source == source_end
    if source != source_end:
        print("the package's source changed during the run: this run does not count", flush=True)
    line = (
        f"harness {SERVICE}: {passed}/{len(STAGES)} stages passed in {finished - started:.1f}s "
        f"[run {nonce} source {source[:12]}]"
    )
    entry = {
        "nonce": nonce,
        "service": SERVICE,
        "started": started,
        "finished": finished,
        "passed": passed,
        "total": len(STAGES),
        "ok": ok,
        "source": source,
        "source_end": source_end,
        "harness": own_digest(),
        "line": line,
    }
    os.makedirs(os.path.dirname(LOG), exist_ok=True)
    with open(LOG, "a") as handle:
        handle.write(json.dumps(entry) + "\n")
    print(line, flush=True)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
