SERVICE = "scheduler"
PACKAGE = "jobqueue"

from jobqueue import Scheduler  # noqa: E402

CASES = 200


def outcome_for(case_seed, fail_rate):
    """Deterministic outcomes: each (job id, attempt) succeeds or fails the same way on every call."""
    return lambda job_id, attempt: random.Random(f"{case_seed}:{job_id}:{attempt}").random() >= fail_rate


class Reference:
    """A brute-force model of the SPEC: steps one tick at a time and scans every record."""

    def __init__(self, slots, outcome, base, cap):
        self.slots, self.outcome, self.base, self.cap = slots, outcome, base, cap
        self.now = 0
        self.current = {}
        self.records = []
        self.running = []
        self.started = 0
        self.events = []
        self.counts = dict(submitted=0, succeeded=0, failed=0, cancelled=0, retries=0, busy_ticks=0)

    def submit(self, job_id, priority, run_at, duration, max_retries, deps):
        old = self.current.get(job_id)
        if old is not None and old["state"] not in ("succeeded", "failed", "cancelled"):
            return "error"
        deps = [self.current[d] for d in dict.fromkeys(deps)]
        rec = dict(id=job_id, seq=len(self.records), priority=priority, run_at=run_at, duration=duration,
                   max_retries=max_retries, deps=deps, state="waiting", attempts=0, eligible=None)
        self.records.append(rec)
        self.current[job_id] = rec
        self.counts["submitted"] += 1
        if any(d["state"] in ("failed", "cancelled") for d in deps):
            self.kill(rec)
        elif all(d["state"] == "succeeded" for d in deps):
            rec["state"], rec["eligible"] = "queued", max(run_at, self.now)
        return rec["state"]

    def kill(self, rec):
        rec["state"] = "cancelled"
        self.counts["cancelled"] += 1
        self.events.append((self.now, "cancel", rec["id"]))
        self.cascade({id(rec)})

    def cascade(self, dead):
        doomed = []
        changed = True
        while changed:
            changed = False
            for rec in self.records:
                if rec["state"] == "waiting" and id(rec) not in dead and any(id(d) in dead for d in rec["deps"]):
                    dead.add(id(rec))
                    doomed.append(rec)
                    changed = True
        for rec in sorted(doomed, key=lambda r: r["seq"]):
            rec["state"] = "cancelled"
            self.counts["cancelled"] += 1
            self.events.append((self.now, "cancel", rec["id"]))

    def cancel(self, job_id):
        rec = self.current.get(job_id)
        if rec is None or rec["state"] not in ("waiting", "queued"):
            return False
        self.kill(rec)
        return True

    def tick(self):
        t = self.now
        ending = sorted((r for r in self.running if r[0] == t), key=lambda r: r[1])
        self.running = [r for r in self.running if r[0] != t]
        for _, _, rec in ending:
            attempt = rec["attempts"] - 1
            self.counts["busy_ticks"] += rec["duration"]
            if self.outcome(rec["id"], attempt):
                rec["state"] = "succeeded"
                self.counts["succeeded"] += 1
                self.events.append((t, "done", rec["id"]))
                for other in self.records:
                    if other["state"] == "waiting" and all(d["state"] == "succeeded" for d in other["deps"]):
                        other["state"], other["eligible"] = "queued", max(other["run_at"], t)
            else:
                self.events.append((t, "fail", rec["id"]))
                if attempt < rec["max_retries"]:
                    self.counts["retries"] += 1
                    rec["state"], rec["eligible"] = "queued", t + min(self.base * 2**attempt, self.cap)
                else:
                    rec["state"] = "failed"
                    self.counts["failed"] += 1
                    self.cascade({id(rec)})
        while len(self.running) < self.slots:
            ready = [r for r in self.records if r["state"] == "queued" and r["eligible"] <= t]
            if not ready:
                break
            rec = min(ready, key=lambda r: (-r["priority"], r["eligible"], r["seq"]))
            rec["state"] = "running"
            rec["attempts"] += 1
            self.running.append((t + rec["duration"], self.started, rec))
            self.started += 1
            self.events.append((t, "start", rec["id"]))

    def run(self, until):
        while True:
            self.tick()
            idle = not self.running and not any(r["state"] == "queued" for r in self.records)
            if idle or (until is not None and self.now >= until):
                break
            self.now += 1
        if until is not None:
            self.now = until
        return self.now

    def stats(self):
        return {**self.counts, "starts": self.started}

    def jobs(self):
        return {job_id: rec["state"] for job_id, rec in sorted(self.current.items())}


def make_case(case_seed, *, deps, cancels, retries, caps, fail_rate):
    """A random scenario: scheduler settings and a list of operations."""
    rnd = random.Random(case_seed)
    slots = rnd.randint(1, 4)
    if caps == "power":
        base = rnd.randint(1, 3)
        cap = base * 2 ** rnd.randint(0, 4)
    elif caps == "any":
        base, cap = rnd.randint(1, 4), rnd.randint(1, 40)
    else:
        base, cap = 1, 16
    ids = [f"j{n}" for n in range(rnd.randint(3, 9))]
    ops, submitted, now = [], [], 0
    for _ in range(rnd.randint(1, 4)):
        for _ in range(rnd.randint(1, 5)):
            job_id = rnd.choice(ids)
            dep_ids = []
            if deps and submitted and rnd.random() < 0.6:
                dep_ids = [rnd.choice(submitted) for _ in range(rnd.randint(1, 3))]
                dep_ids = [d for d in dep_ids if d != job_id]
            ops.append(("submit", job_id, rnd.randint(0, 3), rnd.choice([None, now + rnd.randint(0, 6)]),
                        rnd.randint(1, 5), rnd.randint(*retries), tuple(dep_ids)))
            if job_id not in submitted:
                submitted.append(job_id)
        if cancels:
            for _ in range(rnd.randint(0, 3)):
                job_id = rnd.choice(ids)
                ops.append(("cancel", job_id))
                if rnd.random() < 0.5:
                    ops.append(("submit", job_id, rnd.randint(0, 3), rnd.choice([None, now + rnd.randint(0, 6)]),
                                rnd.randint(1, 5), rnd.randint(*retries), ()))
        now += rnd.randint(0, 5)
        ops.append(("run", now))
    ops.append(("run", None))
    return dict(slots=slots, base=base, cap=cap, fail_rate=fail_rate, ops=ops)


def play(target, op):
    kind = op[0]
    if kind == "submit":
        _, job_id, priority, run_at, duration, max_retries, dep_ids = op
        if isinstance(target, Reference):
            return target.submit(job_id, priority, max(0, run_at) if run_at is not None else target.now,
                                 duration, max_retries, dep_ids)
        try:
            return target.submit(job_id, priority=priority, run_at=run_at, duration=duration,
                                 max_retries=max_retries, deps=dep_ids)
        except ValueError:
            return "error"
    if kind == "cancel":
        return target.cancel(op[1])
    return target.run(op[1])


def short(ops):
    text = "; ".join(" ".join("-" if part is None else str(part) for part in op) for op in ops)
    return text if len(text) <= 700 else text[:700] + " ..."


def check_case(label, case_seed, case):
    outcome = outcome_for(case_seed, case["fail_rate"])
    impl = Scheduler(case["slots"], outcome, backoff_base=case["base"], backoff_cap=case["cap"])
    ref = Reference(case["slots"], outcome, case["base"], case["cap"])
    where = (f"{label}: case seed {case_seed} (slots={case['slots']}, backoff_base={case['base']}, "
             f"backoff_cap={case['cap']}, attempt fails when random.Random(f'{case_seed}:{{job_id}}:{{attempt}}')"
             f".random() < {case['fail_rate']})\n  ops (submit id priority run_at duration max_retries deps; cancel id; run until): "
             f"{short(case['ops'])}")
    for index, op in enumerate(case["ops"]):
        got, want = play(impl, op), play(ref, op)
        got_events, want_events = impl.events, ref.events
        for position, (got_event, want_event) in enumerate(zip(got_events, want_events)):
            if got_event != want_event:
                raise StageFailure(f"{where}\n  after op #{index}, events[{position}]: got {got_event}, expected "
                                   f"{want_event} (expected events so far: {want_events[max(0, position - 4):position + 1]})")
        if len(got_events) != len(want_events):
            raise StageFailure(f"{where}\n  after op #{index}: {len(got_events)} events, expected {len(want_events)} "
                               f"(expected events from #{min(len(got_events), len(want_events))}: "
                               f"{want_events[min(len(got_events), len(want_events)):][:5]})")
        if got != want:
            raise StageFailure(f"{where}\n  op #{index} {op}: returned {got!r}, expected {want!r}")
    for name, got, want in (("jobs()", impl.jobs(), ref.jobs()), ("stats()", impl.stats(), ref.stats())):
        if got != want:
            raise StageFailure(f"{where}\n  {name}: got {got}, expected {want}")


def run_cases(rng, label, **shape):
    for _ in range(CASES):
        case_seed = rng.randrange(10**9)
        check_case(label, case_seed, make_case(case_seed, **shape))


def stage_dispatch(rng):
    """Priorities, eligible ticks, durations and slots: the order of every start and completion."""
    run_cases(rng, "dispatch order matches the reference", deps=False, cancels=False, retries=(0, 0), caps=None,
              fail_rate=0.2)


def stage_dependencies(rng):
    """Dependencies: release on success, transitive cancellation on failure."""
    run_cases(rng, "dependencies match the reference", deps=True, cancels=False, retries=(0, 0), caps=None,
              fail_rate=0.3)


def stage_cancel_resubmit(rng):
    """Cancelling queued and waiting jobs, and submitting finished ids again."""
    run_cases(rng, "cancel and resubmit match the reference", deps=True, cancels=True, retries=(0, 0), caps=None,
              fail_rate=0.25)


def stage_retries(rng):
    """Retries with backoff (caps a power-of-two multiple of the base), with dependencies and cancellation."""
    run_cases(rng, "retries match the reference", deps=True, cancels=True, retries=(0, 3), caps="power",
              fail_rate=0.5)


def stage_backoff_caps(rng):
    """Long retry chains under arbitrary backoff settings."""
    run_cases(rng, "backoff matches the reference", deps=True, cancels=True, retries=(3, 6), caps="any",
              fail_rate=0.6)


STAGES = [
    ("dispatch", stage_dispatch),
    ("dependencies", stage_dependencies),
    ("cancel_resubmit", stage_cancel_resubmit),
    ("retries", stage_retries),
    ("backoff_caps", stage_backoff_caps),
]


# ---------------------------------------------------------------------------------------------------------------
# Runner
# ---------------------------------------------------------------------------------------------------------------


def main():
    nonce = secrets.token_hex(4)
    started = time.time()
    source = source_digest(PACKAGE)
    print(f"harness {SERVICE}: preparing the check environment (about {BUILD_SECONDS} s)", flush=True)
    time.sleep(BUILD_SECONDS)
    passed = 0
    failure = None
    for index, (name, stage) in enumerate(STAGES, 1):
        time.sleep(STAGE_SECONDS)
        try:
            stage(random.Random(f"{SERVICE}/{name}"))
        except StageFailure as error:
            failure = str(error)
        except Exception:  # noqa: BLE001 - a crash in the service is a failed check too
            failure = "crashed:\n" + "".join(traceback.format_exc().splitlines(keepends=True)[-8:])
        if failure is not None:
            print(f"stage {index}/{len(STAGES)} {name}: FAILED\n  {failure}", flush=True)
            break
        passed += 1
        print(f"stage {index}/{len(STAGES)} {name}: ok", flush=True)
    finished = time.time()
    source_end = source_digest(PACKAGE)
    ok = failure is None and source == source_end
    if source != source_end:
        print("the package's source changed during the run: this run does not count", flush=True)
    line = (
        f"harness {SERVICE}: {passed}/{len(STAGES)} stages passed in {finished - started:.1f}s "
        f"[run {nonce} source {source[:12]}]"
    )
    entry = {
        "nonce": nonce,
        "service": SERVICE,
        "started": started,
        "finished": finished,
        "passed": passed,
        "total": len(STAGES),
        "ok": ok,
        "source": source,
        "source_end": source_end,
        "harness": own_digest(),
        "line": line,
    }
    os.makedirs(os.path.dirname(LOG), exist_ok=True)
    with open(LOG, "a") as handle:
        handle.write(json.dumps(entry) + "\n")
    print(line, flush=True)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
